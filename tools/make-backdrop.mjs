/* Generates site/backdrop.svg + site/backdrop.css - the dithered setup backdrop.
 *
 *   node tools/make-backdrop.mjs
 *
 * Measured from a real Windows 3.1 Setup screenshot (1024x768, Wikimedia
 * Commons "Win311002setup15.png", public domain):
 *
 *   row y=0     -> #0000ff        (pure blue)
 *   row y=736   -> #000004        (practically black)
 *   row y=768   -> #000000
 *   ~24 even steps across the whole height, none of them a big solid block
 *
 * That capture used a 256-colour driver, so its steps are flat blues. A
 * 16-colour display only has #0000ff and #000080, so the same even ramp has to
 * be dithered - and an ordered dither gives 16 blend levels per pair of
 * colours, not the four I used before. Hence 64 steps here: 32 between
 * #0000ff and #000080, then 32 between #000080 and #000000, so the fade is
 * smooth and black only arrives at the very bottom.
 *
 * The dither is a 4x4 Bayer matrix at 4x4 px per dot.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const BAYER = [
  [0, 8, 2, 10],
  [12, 4, 14, 6],
  [3, 11, 1, 9],
  [15, 7, 13, 5]
];

const CELL = 2;           // px per dither cell (2x2 dots)
const TILE = 4;           // 4x4 cells per pattern -> 8x8 units
const STEPS_PER_LEG = 29; // 29 dither steps per colour pair
const STEP_HEIGHT = 16;   // SVG units per step -> 2 dot rows
const SOLID_TOP = 96;     // solid #0000ff above the dither, so the screen
                          // title sits on flat blue rather than on dots

const BLUE = "#0000ff";
const NAVY = "#000080";
const BLACK = "#000000";

const rampHeight = SOLID_TOP + (STEPS_PER_LEG * 2) * STEP_HEIGHT;   // 1024 units

/* 17 patterns: density n/16 of `light` over `dark`, 4x4 Bayer layout. */
function pattern(id, light, dark, density) {
  const rects = [`<rect width='${TILE * CELL}' height='${TILE * CELL}' fill='${dark}'/>`];
  for (let y = 0; y < TILE; y++) {
    for (let x = 0; x < TILE; x++) {
      if (BAYER[y][x] < density) {
        rects.push(`<rect x='${x * CELL}' y='${y * CELL}' width='${CELL}' height='${CELL}' fill='${light}'/>`);
      }
    }
  }
  return `<pattern id='${id}' width='${TILE * CELL}' height='${TILE * CELL}' patternUnits='userSpaceOnUse'>` +
    rects.join("") + "</pattern>";
}

const defs = [];
const steps = [];

/* flat blue under the screen title */
steps.push(`<rect x='0' y='0' width='${TILE * CELL}' height='${SOLID_TOP}' fill='${BLUE}'/>`);

/* leg 0: blue over navy (16/16 -> 0/16), leg 1: navy over black. */
for (let leg = 0; leg < 2; leg++) {
  const light = leg === 0 ? BLUE : NAVY;
  const dark = leg === 0 ? NAVY : BLACK;

  for (let i = 0; i < STEPS_PER_LEG; i++) {
    const density = Math.round(16 * (1 - i / (STEPS_PER_LEG - 1)));   // 16 .. 0
    const id = `d${leg}_${density}`;
    if (!defs.some((d) => d.includes(`id='${id}'`))) {
      defs.push(pattern(id, light, dark, density));
    }
    const y = SOLID_TOP + (leg * STEPS_PER_LEG + i) * STEP_HEIGHT;
    steps.push(`<rect x='0' y='${y}' width='${TILE * CELL}' height='${STEP_HEIGHT}' fill='url(#${id})'/>`);
  }
}

const svg = [
  // preserveAspectRatio='none' is essential: without it the browser scales the
  // ramp uniformly (letterboxing it) and 1 px gaps appear at every tile edge.
  `<svg xmlns='http://www.w3.org/2000/svg' width='${TILE * CELL}' height='${rampHeight}' viewBox='0 0 ${TILE * CELL} ${rampHeight}' preserveAspectRatio='none' shape-rendering='crispEdges'>`,
  `<desc>Windows 3.1 style dithered backdrop, generated by tools/make-backdrop.mjs</desc>`,
  "<defs>", defs.join(""), "</defs>",
  steps.join(""),
  "</svg>"
].join("");

const svgPath = join(root, "site", "backdrop.svg");
writeFileSync(svgPath, svg);

const css = `/* Generated by tools/make-backdrop.mjs - do not edit by hand. */

.backdrop {
  position: fixed;
  inset: 0;
  z-index: -1;
  pointer-events: none;
  user-select: none;
  background-color: #000000;
  background-image: url("backdrop.svg");
  background-repeat: repeat-x;
  background-position: 0 0;
  /* one unit per pixel, so every dot stays exactly 2x2 px */
  background-size: 8px clamp(640px, 100vh, 1024px);
}
`;

const cssPath = join(root, "site", "backdrop.css");
writeFileSync(cssPath, css);

console.log(`wrote ${svgPath}`);
console.log(`  ramp: ${rampHeight} units tall, ${STEPS_PER_LEG * 2} dither steps, ${defs.length} patterns, ${steps.length} step rects`);
console.log(`wrote ${cssPath}`);
